package serverpolicy

// This file is the exhaustive App-method -> feature-group map for the
// multi-tenant server build.
//
// It is generated from the exported *App methods at the patch base commit and
// committed as Go source on purpose: the runtime must never depend on the
// generated frontend bindings file, and an unclassified method must fail the
// AST completeness test instead of silently defaulting to "remote".
//
// Source inventory: 388 unique exported *App methods parsed from the root Go
// files at base 60dbd999 (387 of them are present in the generated
// frontend/bindings/github.com/ys-ll/uniterm/app.js at that commit; the
// remaining one is ServiceStartup, which Wails never binds).
//
// Regenerate/verify with TestMethodsCoverEveryAppMethod in ast_test.go.

// Group is one operator-policy feature group.
type Group string

const (
	// GroupTenantFiles is allowed, but every local path argument it accepts is
	// confined to the tenant home, the tenant data/records directory, or the
	// /api/web staging root by serverpolicy.ConfineLocalPath.
	GroupTenantFiles Group = "tenantFiles"
	// GroupTenantStore covers the per-tenant config/state stores.
	GroupTenantStore Group = "tenantStore"
	// GroupMCPClientConfig is the persisted MCP-client configuration surface.
	GroupMCPClientConfig Group = "mcpClientConfig"
	// GroupRemote covers protocols that dial out of the worker (SSH/SFTP, DB,
	// K8s, RDP/VNC/SPICE, AI, sync, settings, netscan) plus remote monitoring.
	GroupRemote Group = "remote"

	GroupLocalServices    Group = "localServices"
	GroupExternalEditor   Group = "externalEditor"
	GroupLocalFilesystem  Group = "localFilesystem"
	GroupNativeDialogs    Group = "nativeDialogs"
	GroupMCPServer        Group = "mcpServer"
	GroupMCPClientProcess Group = "mcpClientProcess"
	GroupUpdate           Group = "update"
	GroupPacketCapture    Group = "packetCapture"
	GroupFirewall         Group = "firewall"
	GroupX11Desktop       Group = "x11Desktop"
	GroupAdmin            Group = "admin"
	// GroupWorkerDocker gates the worker-local Docker/Podman socket. It has no
	// directly-bound methods: every Container* data method takes an established
	// connection ID, and the only way to establish a local connection is the
	// transport guard in ContainerConnect / CreateSession("container-file").
	GroupWorkerDocker Group = "workerDocker"
	// GroupInternal covers optional service hooks Wails never exposes.
	GroupInternal Group = "internal"
)

// Groups lists every group in a stable order.
var Groups = []Group{
	GroupTenantFiles, GroupTenantStore, GroupMCPClientConfig, GroupRemote,
	GroupLocalServices, GroupExternalEditor, GroupLocalFilesystem,
	GroupNativeDialogs, GroupMCPServer, GroupMCPClientProcess, GroupUpdate,
	GroupPacketCapture, GroupFirewall, GroupX11Desktop, GroupAdmin,
	GroupWorkerDocker, GroupInternal,
}

// OptionalGroups are deny-by-default; the operator must set the group to true
// and iAcceptRisk to true before any member method is bound.
var OptionalGroups = []Group{
	GroupLocalServices, GroupExternalEditor, GroupLocalFilesystem,
	GroupNativeDialogs, GroupMCPServer, GroupMCPClientProcess, GroupUpdate,
	GroupPacketCapture, GroupFirewall, GroupX11Desktop, GroupWorkerDocker,
}

// AlwaysAllowedGroups cannot be disabled by the operator.
var AlwaysAllowedGroups = map[Group]bool{
	GroupTenantFiles:     true,
	GroupTenantStore:     true,
	GroupMCPClientConfig: true,
	GroupRemote:          true,
	GroupInternal:        true,
}

// PermanentDeniedGroups stay denied even with iAcceptRisk. The local shell is
// root inside the shared worker, and admin data-dir/reset mutations would break
// every tenant on that worker.
var PermanentDeniedGroups = map[Group]bool{
	GroupAdmin: true,
}

